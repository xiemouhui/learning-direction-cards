test('知识确认撤销保留历史，单平台设置和每日限额刷新后仍有效', async ({ page }) => {
  await page.goto('/knowledge');
  await page.request.get('/api/app');
  const response = await page.request.post('/api/app', { headers: { 'x-app-request': '1', 'idempotency-key': crypto.randomUUID() }, data: { action: 'knowledge', nodeId: 'c', state: { level: 3, evidenceType: 'self', evidence: '虚构撤销测试', learningStatus: 'learning', conflict: false }, baseVersion: 0 } });
  expect(response.ok()).toBe(true);
  await page.reload();
  const event = page.locator('details').filter({ hasText: '虚构撤销测试' });
  await event.locator('summary').click();
  await event.getByRole('button', { name: '撤销这次知识确认' }).click();
  await page.getByRole('button', { name: '取消撤销' }).click();
  expect((await (await page.request.get('/api/app')).json()).knowledge.c.level).toBe(3);
  await event.getByRole('button', { name: '撤销这次知识确认' }).click();
  await page.getByRole('button', { name: '确认撤销知识变化', exact: true }).click();
  await expect(page.getByText('已追加撤销事件，画像已恢复；路线仍需单独比较。', { exact: true })).toBeVisible();
  const state = await (await page.request.get('/api/app')).json();
  expect(state.knowledge.c).toBeUndefined(); expect(state.records.filter((r: { kind: string }) => r.kind === 'event')).toHaveLength(2);
  await page.goto('/settings');
  await page.getByLabel('优先检索平台').selectOption('xiaohongshu');
  await page.getByLabel('每日模型请求上限', { exact: true }).fill('0');
  await page.getByLabel('每日检索请求上限', { exact: true }).fill('0');
  await page.getByLabel('启用所选模型的真实 AI 顾问').check();
  await page.getByLabel('我理解发送范围和可能产生的 API 费用').check();
  await page.getByRole('button', { name: '保存模型与检索设置' }).click();
  await expect(page.getByText('DeepSeek 外部顾问已启用', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('优先检索平台')).toHaveValue('xiaohongshu');
  await expect(page.getByLabel('每日模型请求上限', { exact: true })).toHaveValue('0');
  await page.goto('/advisor');
  await page.getByLabel('本次讨论的专题').selectOption('crypto-engineering');
  await page.getByLabel('关于下一步的疑问').fill('虚构限额测试');
  await page.getByRole('button', { name: '发送给所选模型' }).click();
  await expect(page.getByText(/已达到本身份今日模型调用上限/)).toBeVisible();
  const after = await (await page.request.get('/api/app')).json(); expect(after.services.usage.externalCalls).toBe(0);
});
