import { test, expect } from './fixtures';
import { readFile } from 'node:fs/promises';

test('导出 → 清 Cookie → 预览恢复，保留路线和草稿并拒绝重复覆盖', async ({ page }) => {
  await page.goto('/settings');
  await expect(page.getByRole('button', { name: '下载个人资料 JSON' })).toBeEnabled();
  await page.request.get('/api/app');
  const post = async (data: unknown) => {
    const response = await page.request.post('/api/app', { headers: { 'x-app-request': '1', 'idempotency-key': crypto.randomUUID() }, data });
    expect(response.ok()).toBe(true); return response.json();
  };
  await post({ action: 'knowledge', nodeId: 'c', state: { level: 3, evidenceType: 'task', evidence: '虚构浏览器备份证据', learningStatus: 'learning', conflict: false }, baseVersion: 0 });
  const path = await post({ action: 'savePath', topicId: 'crypto-engineering', mode: 'explore', hours: 3, resources: ['电脑'], startDate: '2026-10-20', baseVersion: 1 });
  await post({ action: 'activate', pathId: path.pathId, baseVersion: 1 });
  await page.evaluate(() => localStorage.setItem('direction-assessment-v1', JSON.stringify({ schemaVersion: 1, answers: Array(10).fill('虚构待提交草稿'), positive: [], negative: [], preference: 'unknown', hours: 3 })));
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载个人资料 JSON' }).click();
  const download = await downloaded;
  const backup = await readFile((await download.path())!, 'utf8');
  await page.context().clearCookies({ name: 'direction_profile' });
  await page.evaluate(() => localStorage.removeItem('direction-assessment-v1'));
  await page.reload();
  await expect(page.getByText('目前没有已保存路线。', { exact: true })).toBeVisible();
  await page.getByLabel('选择个人资料备份 JSON', { exact: true }).setInputFiles({ name: 'fixture-backup.json', mimeType: 'application/json', buffer: Buffer.from(backup) });
  await expect(page.getByText('核对恢复内容', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 375, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.locator('section.panel').filter({ has: page.getByRole('heading', { name: '从备份恢复个人资料', exact: true }) }).screenshot({ path: '.local/recovery-preview-375.png' });
  await expect(page.getByRole('button', { name: '确认恢复备份' })).toBeDisabled();
  await page.getByLabel('恢复确认文字').fill('恢复到空白身份');
  await page.getByRole('button', { name: '确认恢复备份' }).click();
  await expect(page.getByText('备份已恢复。模型与搜索保持关闭，请到知识画像和工作台核对。', { exact: true })).toBeVisible();
  const restored = await (await page.request.get('/api/app')).json();
  expect(restored.knowledge.c.evidence).toBe('虚构浏览器备份证据');
  expect(restored.paths).toHaveLength(1); expect(restored.paths[0].id).not.toBe(path.pathId);
  expect(restored.paths[0].active).toBe(1);
  expect(restored.services.preferences.aiEnabled).toBe(false);
  expect(restored.services.preferences.searchEnabled).toBe(false);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('direction-assessment-v1')!).answers[0])).toBe('虚构待提交草稿');
  await page.getByLabel('选择个人资料备份 JSON', { exact: true }).setInputFiles({ name: 'fixture-backup-again.json', mimeType: 'application/json', buffer: Buffer.from(backup) });
  await page.getByLabel('恢复确认文字').fill('恢复到空白身份');
  await page.getByRole('button', { name: '确认恢复备份' }).click();
  await expect(page.getByText(/仅允许恢复到空白身份；现有资料不会被覆盖/)).toBeVisible();
  expect((await (await page.request.get('/api/app')).json()).paths).toHaveLength(1);
});

