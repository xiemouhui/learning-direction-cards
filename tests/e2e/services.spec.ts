test('账户余额手动查询、失败不冒充零余额，手机用量面板可读', async ({ page }) => {
  let queries = 0;
  await page.route('**/api/app', async route => {
    const action = route.request().method() === 'POST' ? route.request().postDataJSON() : null;
    if (action?.action !== 'account') { await route.continue(); return; }
    queries++;
    await route.fulfill({ json: queries === 1 ? { status: 'success', checkedAt: '2026-10-20T12:00:00.000Z', available: true, balances: [{ currency: 'CNY', total: '12.34', granted: '2.00', toppedUp: '10.34' }] } : { status: 'failed', message: '查询未获授权，请检查 Key 和账户权限。' } });
  });
  await page.goto('/settings');
  const panel = page.getByRole('region', { name: 'DeepSeek 账户信息' });
  await expect(panel.getByText('尚未查询账户信息。', { exact: true })).toBeVisible();
  expect(queries).toBe(0);
  await page.getByRole('button', { name: '刷新 DeepSeek 余额' }).click();
  await expect(panel.getByText('可用余额 12.34 CNY', { exact: true })).toBeVisible();
  await expect(panel.getByText('赠送余额 2.00 · 充值余额 10.34', { exact: true })).toBeVisible();
  await expect(page.getByText('本应用 · 当前身份最近七天用量', { exact: true })).toBeVisible();
  await expect(page.getByRole('region', { name: 'OpenAI 账户信息' })).toContainText('管理密钥');
  await expect(page.getByRole('button', { name: '刷新 Tavily 额度' })).toBeDisabled();
  await page.setViewportSize({ width: 375, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('heading', { name: 'API 余额与用量', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: '.local/account-usage-375.png', fullPage: true });
  await page.getByRole('button', { name: '刷新 DeepSeek 余额' }).click();
  await expect(panel).toContainText('查询未获授权');
  await expect(panel.getByText('可用余额 12.34 CNY', { exact: true })).toHaveCount(0);
  expect(queries).toBe(2);
  // Real local API uses the fixture custom base URL; account credentials must not leave it.
  const response = await page.request.post('/api/app', { headers: { 'x-app-request': '1', 'idempotency-key': crypto.randomUUID() }, data: { action: 'account', provider: 'deepseek' } });
  expect(response.ok()).toBe(true);
  expect(await response.json()).toMatchObject({ status: 'unsupported' });
});
